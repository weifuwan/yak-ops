package io.yak.ops.connector.jdbc.database.catalog;

import java.util.Objects;

/**
 * Physical JDBC column metadata for browsing and preserving vendor-specific display details.
 *
 * <p>Source/Sink type decisions must use JdbcCatalog.getTable(TableId) and its dialect
 * converter, never re-map jdbcType or typeName in the product Business layer.
 *
 * @param name actual column identifier
 * @param typeName JDBC vendor type name
 * @param jdbcType value from java.sql.Types
 * @param size column capacity or precision; nullable when unknown
 * @param scale fractional precision; nullable when unknown
 * @param nullable whether the column can contain SQL NULL
 * @param ordinalPosition physical column order
 * @param primaryKey whether the column belongs to the primary key
 * @param primaryKeyPosition stable KEY_SEQ order, null for non-key fields
 * @param remarks optional column comment
 * @param hasDefaultValue whether a native default expression is declared
 * @param autoIncrement whether values are generated by an identity; null means unknown
 * @param generated whether this is a computed column; null means unknown
 * @param defaultExpression raw JDBC default metadata, never directly executable SQL
 * @param onUpdateExpression native automatic update expression, null when absent
 * @param defaultGenerated MySQL DEFAULT_GENERATED marker, null when not available
 */
public record JdbcColumnInfo(
        String name,
        String typeName,
        int jdbcType,
        Integer size,
        Integer scale,
        boolean nullable,
        int ordinalPosition,
        boolean primaryKey,
        Integer primaryKeyPosition,
        String remarks,
        boolean hasDefaultValue,
        Boolean autoIncrement,
        Boolean generated,
        String defaultExpression,
        String onUpdateExpression,
        Boolean defaultGenerated) {

    public JdbcColumnInfo(
            String name,
            String typeName,
            int jdbcType,
            Integer size,
            Integer scale,
            boolean nullable,
            int ordinalPosition,
            boolean primaryKey,
            Integer primaryKeyPosition,
            String remarks,
            boolean hasDefaultValue,
            Boolean autoIncrement,
            Boolean generated,
            String defaultExpression) {
        this(
                name,
                typeName,
                jdbcType,
                size,
                scale,
                nullable,
                ordinalPosition,
                primaryKey,
                primaryKeyPosition,
                remarks,
                hasDefaultValue,
                autoIncrement,
                generated,
                defaultExpression,
                null,
                null);
    }

    /** Compatibility constructor for callers without a default-expression kind. */
    public JdbcColumnInfo(
            String name,
            String typeName,
            int jdbcType,
            Integer size,
            Integer scale,
            boolean nullable,
            int ordinalPosition,
            boolean primaryKey,
            Integer primaryKeyPosition,
            String remarks,
            boolean hasDefaultValue,
            Boolean autoIncrement,
            Boolean generated,
            String defaultExpression,
            String onUpdateExpression) {
        this(
                name,
                typeName,
                jdbcType,
                size,
                scale,
                nullable,
                ordinalPosition,
                primaryKey,
                primaryKeyPosition,
                remarks,
                hasDefaultValue,
                autoIncrement,
                generated,
                defaultExpression,
                onUpdateExpression,
                null);
    }

    /** Existing constructor for metadata callers that only know the presence of a default. */
    public JdbcColumnInfo(
            String name,
            String typeName,
            int jdbcType,
            Integer size,
            Integer scale,
            boolean nullable,
            int ordinalPosition,
            boolean primaryKey,
            Integer primaryKeyPosition,
            String remarks,
            boolean hasDefaultValue,
            Boolean autoIncrement,
            Boolean generated) {
        this(
                name,
                typeName,
                jdbcType,
                size,
                scale,
                nullable,
                ordinalPosition,
                primaryKey,
                primaryKeyPosition,
                remarks,
                hasDefaultValue,
                autoIncrement,
                generated,
                null,
                null,
                null);
    }

    /** Creates native metadata for plain, explicitly writable columns. */
    public JdbcColumnInfo(
            String name,
            String typeName,
            int jdbcType,
            Integer size,
            Integer scale,
            boolean nullable,
            int ordinalPosition,
            boolean primaryKey,
            Integer primaryKeyPosition,
            String remarks) {
        this(
                name,
                typeName,
                jdbcType,
                size,
                scale,
                nullable,
                ordinalPosition,
                primaryKey,
                primaryKeyPosition,
                remarks,
                false,
                false,
                false,
                null,
                null,
                null);
    }

    public JdbcColumnInfo {
        Objects.requireNonNull(name, "name");
    }
}
