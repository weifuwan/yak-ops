"""Local analysis-script execution backends, in preference order:

1. **cocoon** (`pip install cocoon-sandbox`): cross-platform Rust-kernel sandbox —
   virtual/read-only filesystems (host mounts are read-only by default), Job
   Object process limits, network denied unless `allow_network=True`, wall-clock
   timeout. Verified on Windows: host cwd writes are refused, an explicit
   `work` dir is writable, and a full log analysis round passes inside it.
2. **subprocess fallback** (`LocalRestrictedExecutor`): no OS-level isolation —
   trust model is "the script was generated by our own model"; protections are
   the dedicated workdir, wall-clock timeout, truncated stdout, static pre-check
   and the audit trail.

Production deployments replace both with AgentScope's DockerWorkspace
(FYOIP-16). Either way: the generated SDK is the only I/O surface, writes are
disabled inside scripts, and every execution is audited.
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
import time
from pathlib import Path
from typing import Any

from yak_agent import audit
from yak_agent.sdk_gen import script_rejected, write_sdk

_MAX_OUTPUT_CHARS = 16_000
_DEFAULT_TIMEOUT = 60
_HARD_TIMEOUT_CAP = 300

_AGENT_ROOT = Path(__file__).resolve().parent.parent


def _pick_backend() -> str:
    try:
        import cocoon  # noqa: F401

        return "cocoon"
    except ImportError:
        return "subprocess"


def _truncate(text: str) -> str:
    if len(text) <= _MAX_OUTPUT_CHARS:
        return text
    return text[: _MAX_OUTPUT_CHARS // 2] + "\n...(truncated)...\n" + text[-_MAX_OUTPUT_CHARS // 2 :]


def _run_cocoon(script: Path, workdir: Path, timeout: int) -> tuple[str, str, int]:
    import cocoon

    result = cocoon.run(
        file=str(script),
        runtime="python",
        work=str(workdir),
        timeout=timeout,
        allow_network=True,  # the read-only SDK needs the yak-ops API; the SDK is the only I/O surface
        max_procs=32,
    )
    exit_code = 0 if result.success else (getattr(result, "exit_code", None) or 1)
    return (result.stdout or "", result.stderr or "", exit_code)


def _run_subprocess(script: Path, workdir: Path, timeout: int) -> tuple[str, str, int]:
    try:
        proc = subprocess.run(  # noqa: S603 - fixed interpreter, fixed script path
            [sys.executable, str(script)],
            cwd=str(workdir),
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=timeout,
        )
        return (proc.stdout or "", proc.stderr or "", proc.returncode)
    except subprocess.TimeoutExpired:
        return ("", f"TIMEOUT after {timeout}s", -1)


def run_analysis(
    code: str,
    timeout_seconds: int = _DEFAULT_TIMEOUT,
    workdir: Path | None = None,
    workspace: Any | None = None,
) -> dict[str, Any]:
    """Execute one analysis script and return {stdout, stderr, exitCode, durationMs, backend}.

    `workdir` (a persistent session workspace dir) replaces the ephemeral temp
    directory so scripts can leave files for follow-up rounds. `workspace` is a
    SessionWorkspace: when stdout is truncated the full output is offloaded
    there and the truncation notice carries its path.
    """
    started = time.monotonic()
    timeout = max(5, min(_HARD_TIMEOUT_CAP, int(timeout_seconds)))
    backend = _pick_backend()

    rejection = script_rejected(code)
    if rejection:
        result = {
            "stdout": "",
            "stderr": f"REJECTED: {rejection}",
            "exitCode": -1,
            "durationMs": 0,
            "backend": backend,
        }
        audit.record_tool_call("run_analysis_script", {"code_len": len(code)}, False, 0, rejection)
        return result

    keep = workdir is not None
    workdir = Path(workdir or Path(tempfile.mkdtemp(prefix="yak-ptc-"))).resolve()
    workdir.mkdir(parents=True, exist_ok=True)
    try:
        write_sdk(workdir, _AGENT_ROOT)
        script = workdir / "analysis.py"
        # cocoon's `file=` execution does not put the script's directory on
        # sys.path — inject both the workdir (SDK) and the agent root (yak_client)
        # explicitly; harmless under the subprocess backend.
        preamble = (
            f"import sys; sys.path.insert(0, r\"{workdir}\"); sys.path.insert(0, r\"{_AGENT_ROOT}\")\n"
        )
        script.write_text(preamble + code, encoding="utf-8")

        if backend == "cocoon":
            stdout, stderr, exit_code = _run_cocoon(script, workdir, timeout)
        else:
            stdout, stderr, exit_code = _run_subprocess(script, workdir, timeout)

        truncated = stdout != _truncate(stdout)
        if workspace is not None and truncated:
            rel = workspace.offload("script-stdout", stdout)
            stdout = _truncate(stdout) + f"\n(FULL stdout offloaded to workspace file: {rel}; read it with read_workspace_file)"

        result = {
            "stdout": stdout,
            "stderr": stderr,
            "exitCode": exit_code,
            "durationMs": int((time.monotonic() - started) * 1000),
            "backend": backend,
        }
        ok = exit_code == 0
        audit.record_tool_call(
            "run_analysis_script",
            {"code_len": len(code), "timeout": timeout, "backend": backend},
            ok,
            result["durationMs"],
            None if ok else (stderr or "non-zero exit")[:500],
        )
        return result
    finally:
        if not keep:
            try:
                import shutil

                shutil.rmtree(workdir, ignore_errors=True)
            except Exception:  # noqa: BLE001
                pass


def format_result(result: dict[str, Any]) -> str:
    return json.dumps(result, ensure_ascii=False)
