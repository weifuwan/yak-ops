"""Local restricted executor: runs model-written analysis scripts on this host.

Isolation tier (documented in FYOIP-16): no OS-level sandbox — the trust model
is "the script was generated by our own model". Protections provided:

- dedicated working directory per execution, SDK injected there;
- the SDK hard-disables write operations at import time (HITL stays the only
  mutation path);
- a static pre-check rejects scripts that mention write symbols or escape
  surfaces (subprocess / os.system);
- wall-clock timeout, truncated stdout/stderr, full audit record.

Production deployments replace this tier with AgentScope's DockerWorkspace.
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
import time
from pathlib import Path
from typing import Any

from yak_agent import audit
from yak_agent.sdk_gen import script_rejected, write_sdk

_MAX_OUTPUT_CHARS = 16_000
_DEFAULT_TIMEOUT = 60
_HARD_TIMEOUT_CAP = 300

_AGENT_ROOT = Path(__file__).resolve().parent.parent


def _truncate(text: str) -> str:
    if len(text) <= _MAX_OUTPUT_CHARS:
        return text
    return text[: _MAX_OUTPUT_CHARS // 2] + "\n...(truncated)...\n" + text[-_MAX_OUTPUT_CHARS // 2 :]


def run_analysis(
    code: str,
    timeout_seconds: int = _DEFAULT_TIMEOUT,
    workdir: Path | None = None,
    workspace: Any | None = None,
) -> dict[str, Any]:
    """Execute one analysis script and return {stdout, stderr, exitCode, durationMs}.

    `workdir` (a persistent session workspace dir) replaces the ephemeral temp
    directory so scripts can leave files for follow-up rounds. `workspace` is a
    SessionWorkspace: when stdout is truncated the full output is offloaded
    there and the truncation notice carries its path.
    """
    started = time.monotonic()
    timeout = max(5, min(_HARD_TIMEOUT_CAP, int(timeout_seconds)))

    rejection = script_rejected(code)
    if rejection:
        result = {
            "stdout": "",
            "stderr": f"REJECTED: {rejection}",
            "exitCode": -1,
            "durationMs": 0,
        }
        audit.record_tool_call("run_analysis_script", {"code_len": len(code)}, False, 0, rejection)
        return result

    keep = workdir is not None
    workdir = (workdir or Path(tempfile.mkdtemp(prefix="yak-ptc-")))
    workdir = Path(workdir).resolve()  # subprocess cwd + script path must both be absolute
    workdir.mkdir(parents=True, exist_ok=True)
    try:
        write_sdk(workdir, _AGENT_ROOT)
        (workdir / "analysis.py").write_text(code, encoding="utf-8")
        try:
            proc = subprocess.run(  # noqa: S603 - fixed interpreter, fixed script path
                [sys.executable, str(workdir / "analysis.py")],
                cwd=str(workdir),
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                timeout=timeout,
            )
            stdout = _truncate(proc.stdout)
            if workspace is not None and len(proc.stdout) > len(stdout):
                rel = workspace.offload("script-stdout", proc.stdout)
                stdout += f"\n(FULL stdout offloaded to workspace file: {rel}; read it with read_workspace_file)"
            result = {
                "stdout": stdout,
                "stderr": _truncate(proc.stderr),
                "exitCode": proc.returncode,
                "durationMs": int((time.monotonic() - started) * 1000),
            }
            audit.record_tool_call(
                "run_analysis_script",
                {"code_len": len(code), "timeout": timeout},
                proc.returncode == 0,
                result["durationMs"],
                None if proc.returncode == 0 else (proc.stderr or "non-zero exit")[:500],
            )
            return result
        except subprocess.TimeoutExpired:
            result = {
                "stdout": "",
                "stderr": f"TIMEOUT after {timeout}s",
                "exitCode": -1,
                "durationMs": int((time.monotonic() - started) * 1000),
            }
            audit.record_tool_call(
                "run_analysis_script", {"code_len": len(code), "timeout": timeout}, False,
                result["durationMs"], result["stderr"],
            )
            return result
    finally:
        if not keep:
            try:
                import shutil

                shutil.rmtree(workdir, ignore_errors=True)
            except Exception:  # noqa: BLE001
                pass


def format_result(result: dict[str, Any]) -> str:
    return json.dumps(result, ensure_ascii=False)
